if (!fs.existsSync('shared/core/gameState.js') || !fs.existsSync('shared/battle/turnManager.js')) {
  console.error('Refusing to run: the new layout (shared/core/gameState.js, shared/battle/turnManager.js) is not here.');
  console.error('Unzip refactor.zip into the repository root first, then run this from the repository root.');
  process.exit(1);
}

let removed = 0, gone = 0;
for (const f of REMOVED) {
  if (fs.existsSync(f)) { if (!DRY) fs.rmSync(f); removed++; } else gone++;
}
console.log(`old files removed: ${removed} (already gone: ${gone})`);

// prune directories left empty by the removals
let pruned = 0;
const dirs = new Set();
for (const f of REMOVED) { let d = path.dirname(f); while (d && d !== '.') { dirs.add(d); d = path.dirname(d); } }
for (const d of [...dirs].sort((a, b) => b.length - a.length)) {
  if (fs.existsSync(d) && fs.readdirSync(d).length === 0) { if (!DRY) fs.rmdirSync(d); pruned++; }
}
console.log(`empty folders removed: ${pruned}`);

let moved = 0, bytes = 0;
for (const f of UNUSED_ASSETS) {
  if (!fs.existsSync(f)) continue;
  bytes += fs.statSync(f).size;
  if (DRY) { moved++; continue; }
  if (DELETE_ASSETS) fs.rmSync(f);
  else {
    const dest = path.join('_unused_assets', f);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.renameSync(f, dest);
  }
  moved++;
}
console.log(`${DELETE_ASSETS ? 'deleted' : 'moved to _unused_assets/'}: ${moved} unused assets (${(bytes / 1048576).toFixed(1)} MB)`);
if (!DELETE_ASSETS && !DRY) console.log('Review _unused_assets/, then delete it (or add it to .gitignore) when you are happy.');
