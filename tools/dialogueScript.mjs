// tools/dialogueScript.mjs: `npm run dialogue` writes every encounter's spoken lines, in play order, to docs/encounter-dialogue.md (with titles,
// choices and where they lead) and to docs/encounter-script.txt (just the words, plain text, for editing: see SCRIPT_HELP for its marks).
// It reads the encounters themselves (shared/story/encounterDefinitions.js), so it is never out of date: run it again after changing any text.
// What is listed is what a recorded voice will read: each stage's text and the action line a choice says when picked. Stage titles and
// button labels are shown for orientation (they are on screen, not spoken).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { encounterDefinitions } from '../shared/story/encounterDefinitions.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs', 'encounter-dialogue.md');
const SCRIPT_OUT = path.join(ROOT, 'docs', 'encounter-script.txt');

// Who speaks a stage's quoted words (everything unquoted is the narrator). Encounter id -> stage id pattern -> speaker.
const SPEAKERS = { mysterious_altar: [[/^darius_/, 'DARIUS']], hooded_stranger: [[/./, 'STRANGER']] };
const speakerOf = (encId, stageId) => ((SPEAKERS[encId] || []).find(([re]) => re.test(stageId)) || [])[1] || null;
// A stage's text as script lines: with a speaker, each quoted run is that speaker's line and the words between are the narrator's.
function scriptLines(text, speaker) {
    if (!speaker) return [text];
    const out = [];
    for (const m of String(text).matchAll(/"([^"]*)"|([^"]+)/g)) {
        if (m[1] !== undefined) out.push(`${speaker}: "${m[1]}"`);
        else if (m[2].trim()) out.push(m[2].trim());
    }
    return out;
}

const SCRIPT_HELP = `ENCOUNTER SCRIPT
Generated by \`npm run dialogue\` from the game's encounter files. Edit the words freely, then send it back (or push it) and the
changes are put into the encounters. Lines are only the words that are read aloud.

HOW IT IS LAID OUT
  ===== TITLE (encounter_id) =====   one encounter
  [stage_id]                         one screen of the encounter. Leave these tags as they are: they say where the words go.
  plain text                         what the narrator reads (and what is shown)
  > Choice label                     a button (shown, never read). Its own line under it, if any, is read when it is picked.

MARKS YOU CAN ADD
  [pause]          a beat of silence in the reading, about a second   e.g.  The door creaks. [pause] Nothing moves.
  [pause 3]        a pause of that many seconds
  ---              on a line of its own inside a stage: a stage break. What follows becomes the next screen, behind a
                   "Continue." button (as with Darius's silent "......")
  (( words ))      shown on screen but not read aloud
  NAME: "words"    read by that character's voice, not the narrator's (one voice per name: DARIUS, MERCHANT, ...)

Write "you" for the player: a recorded voice cannot say a name the player chose.
`;

const outcomesOf = (d) => [...(d.outcomes || []), ...(d.successOutcomes || []), ...(d.failureOutcomes || [])];
const nextStages = (d) => outcomesOf(d).flatMap(o => o.results || []).filter(r => r.type === 'ADVANCE_STAGE').map(r => r.payload.stageId);
const where = (d) => {
    const results = outcomesOf(d).flatMap(o => o.results || []);
    const to = [...new Set(nextStages(d))];
    const bits = [];
    if (d.type === 'skill_check') {
        const ok = [...new Set((d.successOutcomes || []).flatMap(o => o.results || []).filter(r => r.type === 'ADVANCE_STAGE').map(r => r.payload.stageId))];
        const no = [...new Set((d.failureOutcomes || []).flatMap(o => o.results || []).filter(r => r.type === 'ADVANCE_STAGE').map(r => r.payload.stageId))];
        bits.push(`roll ${String(d.attribute || '').slice(0, 3).toUpperCase()} ${d.threshold}: pass → ${ok.join(' / ') || 'end'}, fail → ${no.join(' / ') || 'end'}`);
    } else if (to.length) bits.push(`→ ${to.join(' / ')}`);
    if (results.some(r => r.type === 'START_BATTLE')) bits.push('fight');
    if (results.some(r => r.type === 'END_ENCOUNTER')) bits.push('ends');
    if (d.type === 'switch_character') bits.push('switch party member');
    return bits.join(', ');
};

// stages in the order a player meets them: from the first stage, each branch followed to its end before the next (so a scene reads in one
// piece); any stages nothing leads to are listed after
function orderedStages(enc) {
    const stages = enc.stages || {};
    const order = [];
    const visit = (id) => {
        if (!id || order.includes(id) || !stages[id]) return;
        order.push(id);
        for (const d of stages[id].decisions || []) for (const n of nextStages(d)) visit(n);
    };
    visit(enc.initialStage || Object.keys(stages)[0]);
    for (const id of Object.keys(stages)) visit(id);
    return order;
}

const quote = (t) => String(t).replace(/\n/g, '\n> ');
let chars = 0, lines = 0;
const spoken = (t) => { chars += String(t).length; lines++; return t; };

const parts = [];
const encounters = Object.values(encounterDefinitions).filter(e => e && e.id !== 'test_encounter');
encounters.sort((a, b) => String(a.title || a.id).localeCompare(String(b.title || b.id)));

for (const enc of encounters) {
    parts.push(`## ${enc.title || enc.id}`, '', `\`${enc.id}\``, '');
    for (const id of orderedStages(enc)) {
        const st = enc.stages[id];
        parts.push(`### ${st.displayText || id}  \`${id}\``, '');
        if (st.text) parts.push(`> ${quote(spoken(st.text))}`, '');
        for (const d of st.decisions || []) {
            const how = where(d);
            parts.push(`- **${d.text}**${how ? `  _(${how})_` : ''}`);
            if (d.customActionText) parts.push(`  - _spoken:_ ${spoken(d.customActionText)}`);
        }
        parts.push('');
    }
}

const head = [
    '# Encounter dialogue',
    '',
    `Generated by \`npm run dialogue\` from the game's encounter files. ${encounters.length} encounters, ${lines} spoken lines, ${chars.toLocaleString('en-US')} characters.`,
    '',
    'Quoted blocks are what the narrator (or the speaking character) reads. A line under a choice marked _spoken_ is read when that choice is picked.',
    'Choice labels and stage titles are on screen only. Edit the text in the encounter files (shared/story/encounters/), then run `npm run dialogue` again.',
    '',
    '## Contents',
    '',
    ...encounters.map(e => `- [${e.title || e.id}](#${String(e.title || e.id).toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')})`),
    '',
];
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, [...head, ...parts].join('\n'));
const script = [SCRIPT_HELP];
for (const enc of encounters) {
    script.push('', '', `===== ${String(enc.title || enc.id).toUpperCase()} (${enc.id}) =====`);
    for (const id of orderedStages(enc)) {
        const st = enc.stages[id];
        script.push('', `[${id}]`);
        if (st.text) script.push(...scriptLines(st.text, speakerOf(enc.id, id)));
        for (const d of st.decisions || []) {
            script.push(`  > ${d.text}`);
            if (d.customActionText) script.push(`      ${d.customActionText}`);
        }
    }
}
fs.writeFileSync(SCRIPT_OUT, script.join('\n') + '\n');
console.log(`Wrote ${path.relative(ROOT, OUT)} and ${path.relative(ROOT, SCRIPT_OUT)}: ${encounters.length} encounters, ${lines} spoken lines, ${chars} characters.`);
